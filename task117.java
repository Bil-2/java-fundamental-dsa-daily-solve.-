public class task117 {//max of two numbers//
    public static void main(String[] args) {
        int a = 32;
        int b = 31;
        int max;
        if (a > b) {
            max = a;
        } else {
            max = b;
        }
        System.out.println("The maximum of two numbers is: " + max);
    }
}   
